#!/usr/bin/env python3
"""Generate lib/life/quotes/quote_data.dart from tool/quotes/quotes.json.

Run from the repository root (Python 3 standard library only):

    python3 -I tool/generate_quotes.py

The JSON keeps the verification notes and URLs; the Dart file only gets what
the app shows (id, text, author, source) plus themes and life stages.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tool' / 'quotes' / 'quotes.json'
TARGET = ROOT / 'lib' / 'life' / 'quotes' / 'quote_data.dart'
LANGUAGES = ('en', 'de', 'fr', 'es')
STAGES = ('young', 'exploring', 'building', 'midlife', 'harvest', 'wisdom')


def dart_string(value):
    """A single-quoted Dart literal; non-ASCII spaces become \\u escapes."""
    out = []
    for char in value:
        if char in '\\\'$':
            out.append('\\' + char)
        elif char == '\n':
            out.append('\\n')
        elif char in '   ':
            out.append('\\u%04X' % ord(char))
        else:
            out.append(char)
    return "'" + ''.join(out) + "'"


def language_map(values, indent):
    pad = ' ' * indent
    lines = ['{']
    for language in LANGUAGES:
        lines.append(f'{pad}  \'{language}\': {dart_string(values[language])},')
    lines.append(pad + '}')
    return '\n'.join(lines)


def validate(quotes):
    ids = set()
    for quote in quotes:
        qid = quote['id']
        if qid in ids:
            sys.exit(f'duplicate id {qid}')
        ids.add(qid)
        for language in LANGUAGES:
            if not quote['text'][language].strip():
                sys.exit(f'{qid}: empty {language} text')
            if quote['author'] and not quote['author'][language].strip():
                sys.exit(f'{qid}: empty {language} author')
        if quote['author'] and not quote['source']:
            sys.exit(f'{qid}: authored quote without source')
        for stage in quote['stages']:
            if stage not in STAGES:
                sys.exit(f'{qid}: unknown stage {stage}')


def entry(quote):
    lines = ['  QuoteEntry(', f'    id: {dart_string(quote["id"])},']
    lines.append(f'    text: {language_map(quote["text"], 4)},')
    if quote['author']:
        lines.append(f'    author: {language_map(quote["author"], 4)},')
    if quote['source']:
        lines.append(f'    source: {dart_string(quote["source"])},')
    if quote['themes']:
        themes = ', '.join(dart_string(t) for t in quote['themes'])
        lines.append(f'    themes: [{themes}],')
    if quote['stages']:
        stages = ', '.join(f'LifeStage.{s}' for s in quote['stages'])
        lines.append(f'    stages: [{stages}],')
    lines.append('  ),')
    return '\n'.join(lines)


def main():
    quotes = json.loads(SOURCE.read_text(encoding='utf-8'))
    validate(quotes)
    header = (
        '// GENERATED by tool/generate_quotes.py from tool/quotes/quotes.json.\n'
        '// Do not edit by hand: change the JSON and run\n'
        '//   python3 -I tool/generate_quotes.py\n\n'
        "import 'package:memento_mori_life_in_weeks/life/life_stage.dart';\n"
        "import 'package:memento_mori_life_in_weeks/life/quotes/quote_entry.dart';\n\n"
        '/// Every life quote, in collection order (the same set for every language).\n'
        'const List<QuoteEntry> quoteEntries = [\n'
    )
    body = '\n'.join(entry(q) for q in quotes)
    TARGET.write_text(header + body + '\n];\n', encoding='utf-8')
    print(f'{len(quotes)} quotes -> {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
